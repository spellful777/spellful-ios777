async function seed() {
  console.log('Seeding spells...');

  for (const spell of SPELLS) {
    const slug = slugify(spell.title);
    try {
      await db.insert(spells).values({
        slug,
        title: spell.title,
        subtitle: spell.subtitle,
        purpose: spell.purpose,
        intention: spell.intention,
        difficulty: spell.difficulty,
        durationMinutes: spell.durationMinutes,
        moonPhase: spell.moonPhase,
        bestTiming: spell.bestTiming,
        materials: spell.materials,
        steps: spell.steps,
        safetyNotes: spell.safetyNotes,
        herbCorrespondences: spell.herbCorrespondences,
        crystalCorrespondences: spell.crystalCorrespondences,
        elementCorrespondences: spell.elementCorrespondences,
        relatedSpellIds: [],
        status: 'approved',
        isAdminCreated: true,
        isFeatured: spell.isFeatured,
        saveCount: 0,
        ratingCount: 0,
        ratingSum: 0,
      });
      console.log(`  ✓ ${spell.title}`);
    } catch (err: unknown) {
      const msg = err instanceof Error ? err.message : String(err);
      if (msg.includes('Duplicate entry')) {
        console.log(`  ~ ${spell.title} (already exists, skipping)`);
      } else {
        console.error(`  ✗ ${spell.title}: ${msg}`);
      }
    }
  }

  console.log('Done seeding spells.');
  process.exit(0);
}

seed().catch((err) => {
  console.error(err);
  process.exit(1);
});
