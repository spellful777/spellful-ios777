const cols = [
  'name','aliases','category','botanical_name','plant_family','plant_part','region',
  'element','planet','zodiac','magical_uses','spell_types','best_timing','moon_phase',
  'notes','spell_components','source_label','tradition_attribution','correspondence_provenance',
  'safety_notes','pregnancy_caution','pet_toxicity','drug_interactions',
  'ingestion_warning','smoke_warning','topical_warning','identity_warning',
  'citation_url','last_verified_date','status',
];

let inserted = 0;
let skipped = 0;

for (const h of NEW_HERBS) {
  try {
    const vals = [
      h.name, h.aliases ?? '', h.category,
      h.botanicalName ?? '', h.plantFamily ?? '', h.plantPart ?? '', h.region ?? '',
      h.element ?? '', h.planet ?? '', h.zodiac ?? '',
      h.magicalUses, h.spellTypes, h.bestTiming, h.moonPhase ?? '',
      h.notes ?? '', h.spellComponents ?? '',
      h.sourceLabel ?? 'TRADITIONAL CORRESPONDENCE',
      h.traditionAttribution ?? '', h.correspondenceProvenance ?? '',
      h.safetyNotes ?? null,
      h.pregnancyCaution ? 1 : 0,
      h.petToxicity ? 1 : 0,
      h.drugInteractions ?? null,
      h.ingestionWarning ?? null,
      h.smokeWarning ?? null,
      h.topicalWarning ?? null,
      h.identityWarning ?? null,
      h.citationUrl ?? '', h.lastVerifiedDate ?? '',
      h.status ?? 'approved',
    ];
    const placeholders = cols.map(() => '?').join(', ');
    await conn.execute(
      `INSERT IGNORE INTO herbs (${cols.join(', ')}) VALUES (${placeholders})`,
      vals
    );
    inserted++;
    process.stdout.write(`✓ ${h.name}\n`);
  } catch (err) {
    skipped++;
    console.error(`✗ ${h.name}: ${err.message}`);
  }
}

await conn.end();
console.log(`\nSeed complete. Inserted: ${inserted}, Skipped (duplicates): ${skipped}`);
